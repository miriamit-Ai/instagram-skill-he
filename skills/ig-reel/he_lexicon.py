"""
he_lexicon.py - Hebrew support for hookscore.py and beats.py (Miriam AI Hebrew edition).

Hebrew glues small words onto the front of the next word (ו, ה, ב, ל, מ, ש, כ),
so "והטעות" has to match "טעות". Every lookup here tries the word as written and
then with up to two of those prefix letters removed.

Spoken Hebrew is slower in words per minute than English, because one Hebrew word
often carries what English says in two or three. The default rate for Hebrew is
150 words per minute (measured on a real Hebrew reel); time yourself and pass --wpm.
"""
import re

HEB = "֐-׿"
HEB_RE = re.compile(f"[{HEB}]")
# niqqud and cantillation marks are stripped before matching
NIQQUD_RE = re.compile("[֑-ׇ]")
WORD_RE = re.compile(f"[{HEB}A-Za-z0-9$₪%'’\"״׳-]+")
PREFIXES = "והבלמשכ"
DEFAULT_WPM = 150  # measured on a fast Hebrew reel by Miriam AI: 143 words in 56.6s


def is_hebrew(text):
    return len(HEB_RE.findall(text)) >= 3


def norm(w):
    return NIQQUD_RE.sub("", w).strip("'’\"״׳-.,!?:;").lower()


def variants(w):
    """the word, and the word with one or two prefix letters removed"""
    w = norm(w)
    out = [w]
    if len(w) > 2 and w[0] in PREFIXES:
        out.append(w[1:])
        if len(w) > 3 and w[1] in PREFIXES:
            out.append(w[2:])
    return out


def hit(w, vocab):
    return any(v in vocab for v in variants(w))


